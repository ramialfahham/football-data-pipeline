"""Generate the metric docs blocks and the metric map from `metric_catalogue.csv`, and check they match.

The map, `seeds/metric_map.csv`, says where each catalogue metric can be read: one row per mart
column that references a metric's block, and one per metric a long-format mart holds in
`metric_key`. Every catalogue metric must have a row.

#82 step 4. The catalogue is this project's only source of what a metric MEANS
(`dbt_project/seeds/schema.yml`: "The single source of truth for every metric we
compute"). The same vocabulary is also 501 columns spread across 11 model ymls,
and until now those columns carried no description at all. Writing them by hand
would have created a second source that drifts from the seed, which is the exact
failure this programme exists to remove — `league_code` reached 76 descriptions in
22 wordings that way.

So the blocks are GENERATED and never authored. Edit the seed; regenerate. The
ruling this meets: docs blocks are used only with a mechanism that applies them
consistently.

WHY ONE SCRIPT WITH `--check` RATHER THAN A GENERATOR AND A SEPARATE CHECKER, the
`sync_dbt_vars.py` + `check_registry_var_sync.py` shape: two files must each
compute the expected output, and the two copies drift. Here `_render()` is the
single definition of what correct looks like, and both modes call it.

⚠ IT EMITS A BLOCK FOR EVERY METRIC, deliberately, not only for the columns that
happen to be blank today. That keeps the output a pure function of the seed, so a
fresh run reproduces the file byte for byte. An earlier draft's name-scoped
refusal meant the shipped diff could not be regenerated by the tool that produced
it. The alternative was a hand-maintained list of metrics to skip, which is the
same anti-pattern as an exemption list.

⛔ ONE NAME CAN MEAN TWO THINGS AND THE SCRIPT MUST NOT GUESS. The catalogue's real
key is `(metric_id, entity)`, not `metric_id`. Where a metric's rows disagree, this
emits one block PER ENTITY (`<metric>__team` / `<metric>__player`) so nothing has to
pick a winner, and it ABORTS if it cannot tell the rows apart. Six columns were wired
to the wrong meaning of `league_code` in MR3 by a tool that assumed one name means one
thing; that assumption is not repeated here.

⚠ THE WORKED EXAMPLE WAS `goals_open_play` — the authoritative scoreline minus
penalties and own goals for a TEAM, and total goals minus penalties for a PLAYER.
**That example is HISTORICAL**, and so is every other: step 4 of the naming programme
renamed all six colliding player ids (`duels_won_pct`, `saves`, `goals_against`,
`goals`, `goals_open_play`, `goals_penalty`), so **no metric in the catalogue disagrees
across entities any more.** The split is kept deliberately: `(metric_id, entity)` is
still the seed's real key, `_derived()` still suffixes unconditionally, and one new
seed row is all it takes to recreate the collision. A guard with no live instance is
not the same as a guard that was wrong.

Usage:

    python scripts/sync_metric_docs_blocks.py            # write the file
    python scripts/sync_metric_docs_blocks.py --check    # fail if it has drifted
"""
from __future__ import annotations

import argparse
import csv
import io
import pathlib
import re
import sys
import textwrap

import yaml

REPO_ROOT = pathlib.Path(__file__).resolve().parents[1]
SEED = REPO_ROOT / "dbt_project" / "seeds" / "metric_catalogue.csv"
MODELS = REPO_ROOT / "dbt_project" / "models"

# Must live under `models/`: dbt reads docs blocks from the default `docs-paths`, and a block
# outside it renders as literal text.
OUT = REPO_ROOT / "dbt_project" / "models" / "docs" / "metric_columns.md"

MAP_OUT = REPO_ROOT / "dbt_project" / "seeds" / "metric_map.csv"
MARTS_DIR = "5_marts"
MAP_FIELDS = ("table_name", "column_name", "metric_id", "variant", "window_column",
              "metric_key_column")
WINDOW_COLUMN = "window_type"
METRIC_KEY_COLUMN = "metric_key"
LONG_VALUE_COLUMNS = ("metric_value", "sort_value")
DOC_REF = re.compile(r"doc\(\s*['\"](\w+)['\"]\s*\)")

# A column name says which part of a metric it holds: a side, a period, or both.
VARIANT_SIDES = (
    ("prefix", "home_", "home"),
    ("prefix", "away_", "away"),
    ("suffix", "_home", "home"),
    ("suffix", "_away", "away"),
    ("prefix", "opponent_", "opponent"),
    ("prefix", "last_meeting_", "last_meeting"),
    ("prefix", "recent_meetings.", "recent_meetings"),
)
VARIANT_PERIODS = (
    ("suffix", "_prev_season_full", "prev_season_full"),
    ("suffix", "_prev_season", "prev_season"),
    ("suffix", "_this_season", "this_season"),
    ("suffix", "_delta_yoy", "delta_yoy"),
    ("suffix", "_sum_season", "sum_season"),
    ("suffix", "_sum_form", "form"),
    ("suffix", "_recent", "form"),
)

# Floor under the read: a read matching nothing would emit an empty file and delete every
# definition.
MIN_METRICS = 50

# A catalogue row is window-free, so any occurrence of the word is wrong; match the word alone.
WINDOW_PHRASING = re.compile(r"\bwindow\b", re.I)

# The parts of engineering_standards.md section 2 ("A metric's description") a machine can hold.
DESCRIPTION_MAX = 200
SNAKE_CASE_NAME = re.compile(r"\b[a-z0-9]+(?:_[a-z0-9]+)+\b", re.I)
LISTED_WORD = re.compile(
    r"\b(?:null|provider|api|displayed|shown as|retired|formerly|normalised|aggregated)\b", re.I
)


def _description_fault(text: str) -> str | None:
    if len(text) > DESCRIPTION_MAX:
        return f"{len(text)} characters, over {DESCRIPTION_MAX}"
    found = SNAKE_CASE_NAME.search(text) or LISTED_WORD.search(text)
    return f"says {found.group(0)!r}" if found else None


def _definition(row: dict) -> str:
    """The seed's description, as written: when a value is blank is a rule of the catalogue table's
    own description, stated once there, never appended to a metric's."""
    return (row["description"] or "").strip()

# --- derived columns ---
# A derived column is a catalogue metric with one standard affix; its block is the seed's
# definition followed by the affix's sentence.
# The phrases stay neutral about what a "match" is, because team models align by games played and
# player models by appearances while sharing the same affixes.
DERIVED_AFFIXES: tuple[tuple[str, str, str], ...] = (
    ("_per_match_this_season", "suffix",
     "Divided by matches played, for the season now in progress, through the matches played so "
     "far."),
    ("_per_match_prev_season", "suffix",
     "Divided by matches played, for the season before, through the same number of matches as "
     "the current season has played so far, so the two are compared at the same point of a "
     "campaign rather than a part season against a full one."),
    ("_per_match_delta_yoy", "suffix",
     "The change in the per-match value from the previous season to the current one, compared at "
     "the same point of the campaign: the current value minus the previous one."),
    ("_prev_season_full", "suffix",
     "The previous season's complete total, with no cutoff. It is context for how large that "
     "season was and is never subtracted from the season in progress, because a part season "
     "against a full one would mislead."),
    ("_prev_season", "suffix",
     "Value for the season before, through the same number of matches as the current season has "
     "played so far. So the two are compared at the same point of a campaign rather than a part "
     "season against a full one."),
    ("_this_season", "suffix",
     "Value for the season now in progress, accumulated through the matches played so far."),
    ("_delta_yoy", "suffix",
     "The change from the previous season to the current one, compared at the same point of the "
     "campaign: the current value minus the previous one."),
    ("_sum_season", "suffix", "Totalled over the season."),
    ("last_meeting_", "prefix",
     "Taken from the most recent previous meeting between these two teams."),
    ("opponent_", "prefix", "Measured for the opposing team rather than this one."),
)

# A block name must match `\w+`, the pattern dbt uses for both the docs tag and `doc()`; a dotted
# name would be unaddressable.
BLOCK_NAME_RE = re.compile(r"^\w+$")

# Floor under the derived names read from the model YAML, for the same reason as MIN_METRICS.
MIN_DERIVED = 40

# Affixes that total a value; a metric with a `denominator_expr` is a rate, and totalling it is a
# different quantity, so its block is refused and the column stays blank.
TOTALLING_AFFIXES = ("_sum_season",)

WRAP = 95

HEADER = """<!--
GENERATED FILE - DO NOT EDIT BY HAND.

Every block below is produced from dbt_project/seeds/metric_catalogue.csv by
scripts/sync_metric_docs_blocks.py. To change a definition, change the seed's
`description` and regenerate; an edit made here is overwritten and, until it is,
makes the seed and the warehouse disagree about what a metric means.

    python scripts/sync_metric_docs_blocks.py

A metric whose team and player rows define it differently gets one block per
entity, suffixed __team / __player, so no caller has to guess which meaning it is
pointing at.

Blocks are also emitted for DERIVED column names - a metric with one standard
affix on it, such as goals_against_sum_season or duels_won_pct_this_season. Those
are the seed's definition followed by the affix's own sentence, and they exist for
exactly the column names the model YAML contains, so adding a column shaped that
way and forgetting to regenerate fails the drift check in CI.
-->
"""


class Abort(Exception):
    """The input is not what this script knows how to read. Never guess."""


def _read_rows() -> list[dict]:
    if not SEED.exists():
        raise Abort("seed not found: " + str(SEED))
    with open(SEED, encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh))
    if len(rows) < MIN_METRICS:
        raise Abort(
            "read only " + str(len(rows)) + " catalogue rows (floor " + str(MIN_METRICS)
            + "). The read has stopped matching - a generator over zero rows would "
            "emit an empty file and delete every definition."
        )
    for r in rows:
        for field in ("metric_id", "entity", "description"):
            if not (r.get(field) or "").strip():
                raise Abort(
                    "row " + repr(r.get("metric_id")) + " has an empty " + field
                    + ". Every metric must define itself; an empty slot here becomes "
                    "an empty description on every column of that name."
                )
    return rows


def _blocks(rows: list[dict]) -> dict[str, str]:
    """One block per metric where its rows agree, one per entity where they do not."""
    by_metric: dict[str, list[dict]] = {}
    for r in rows:
        by_metric.setdefault(r["metric_id"].strip(), []).append(r)

    blocks: dict[str, str] = {}
    for metric, group in by_metric.items():
        texts = {_definition(r) for r in group}
        if len(texts) == 1:
            blocks[metric] = texts.pop()
            continue
        # Rows that disagree split on entity; if two share an entity there is no key to split on.
        entities = [(r["entity"] or "").strip() for r in group]
        if len(set(entities)) != len(entities):
            raise Abort(
                "metric " + repr(metric) + " has rows that define it differently but "
                "share an entity, so there is no key to tell them apart. Fix the "
                "seed; this script will not choose one."
            )
        for r in group:
            suffix = (r["entity"] or "").strip().replace(" ", "_")
            blocks[metric + "__" + suffix] = _definition(r)
    return blocks


def _column_names() -> list[str]:
    """Every column name declared under `models/`, read from the YAML because it must run offline."""
    names: set[str] = set()
    for path in sorted(MODELS.rglob("*.yml")):
        rel = _rel(path)
        if "/target/" in f"/{rel}" or "/dbt_packages/" in f"/{rel}":
            continue
        for _, columns in _models_in(path):
            names.update(col["name"] for col in columns)
    return sorted(names)


def _models_in(path: pathlib.Path) -> list[tuple[str, list[dict]]]:
    """(model name, its named columns) for every model a yml declares."""
    try:
        doc = yaml.safe_load(path.read_text(encoding="utf-8"))
    except (yaml.YAMLError, UnicodeDecodeError, OSError) as exc:
        # An unparsable file leaves the name set incomplete, which would silently drop blocks.
        raise Abort(_rel(path) + " will not parse (" + exc.__class__.__name__
                    + "), so the column-name set is incomplete and any block "
                    "missing from the output would be missing for that reason "
                    "rather than because the column does not exist.") from exc
    if not isinstance(doc, dict) or not isinstance(doc.get("models"), list):
        return []
    return [
        (model["name"], [col for col in model.get("columns") or []
                         if isinstance(col, dict) and isinstance(col.get("name"), str)])
        for model in doc["models"]
        if isinstance(model, dict) and isinstance(model.get("name"), str)
    ]


def _decompose(name: str, metrics: set[str]) -> tuple[str, str] | None:
    """(metric_id, affix) for a name with exactly one affix on a real metric, else None."""
    hits: list[tuple[str, str]] = []
    for affix, kind, _ in DERIVED_AFFIXES:
        if kind == "suffix" and name.endswith(affix):
            stem = name[: -len(affix)]
        elif kind == "prefix" and name.startswith(affix):
            stem = name[len(affix):]
        else:
            continue
        if stem in metrics:
            hits.append((stem, affix))
    if not hits:
        return None
    # The longest stem wins so a rate such as `goals_per_match` keeps its own catalogue definition
    # rather than being composed from `goals`.
    return max(hits, key=lambda h: len(h[0]))


def _derived_blocks(rows: list[dict], names: list[str],
                    refused: list[str] | None = None) -> dict[str, str]:
    """One block per derived column name, always entity-suffixed so no column takes the wrong entity."""
    phrases = {affix: phrase for affix, _, phrase in DERIVED_AFFIXES}
    rated = {r["metric_id"].strip() for r in rows
             if (r.get("denominator_expr") or "").strip()}
    by_entity: dict[str, dict[str, str]] = {}
    for r in rows:
        metric = r["metric_id"].strip()
        entity = (r["entity"] or "").strip().replace(" ", "_")
        text = _definition(r)
        # Two rows sharing a metric and an entity while disagreeing are already aborted on in
        # `_blocks()`.
        by_entity.setdefault(metric, {})[entity] = text

    out: dict[str, str] = {}
    found = 0
    for name in names:
        hit = _decompose(name, set(by_entity))
        if not hit:
            continue
        stem, affix = hit
        if affix in TOTALLING_AFFIXES and stem in rated:
            # Reported rather than skipped: with no block the wiring tool cannot see this column.
            if refused is not None:
                refused.append(name + " (totalling the rate metric " + stem + ")")
            continue
        found += 1
        for entity, text in by_entity[stem].items():
            out[name + "__" + entity] = text + " " + phrases[affix]
    bad = sorted(n for n in out if not BLOCK_NAME_RE.match(n))
    if bad:
        raise Abort(
            "these block names are not addressable by dbt, which matches `\\w+` in "
            "both the docs tag and `doc()`: " + ", ".join(bad) + ". A block dbt "
            "cannot address renders as literal text in the warehouse, and the "
            "drift reporter would not even list it as missing, because its own "
            "regex skips the dot."
        )
    if found < MIN_DERIVED:
        raise Abort(
            "matched only " + str(found) + " derived column names (floor "
            + str(MIN_DERIVED) + "). The column-name read or the affix list has "
            "stopped matching, and emitting fewer blocks would blank every column "
            "whose block disappeared."
        )
    return out


def _render(rows: list[dict], names: list[str],
            refused: list[str] | None = None) -> bytes:
    blocks = _blocks(rows)
    derived = _derived_blocks(rows, names, refused)
    clash = sorted(set(blocks) & set(derived))
    if clash:
        raise Abort(
            "these names are produced BOTH as a metric block and as a derived "
            "block, so one would silently overwrite the other: " + ", ".join(clash)
        )
    blocks.update(derived)

    offenders = sorted(n for n, t in blocks.items() if WINDOW_PHRASING.search(t))
    if offenders:
        raise Abort(
            "these definitions still describe a window, which is false on a "
            "per-match column and contradicts the seed's own contract: "
            + ", ".join(offenders)
        )

    faults = sorted(
        f"{r['metric_id']} ({r['entity']}): {fault}"
        for r in rows
        if (fault := _description_fault(_definition(r)))
    )
    if faults:
        raise Abort(
            "these descriptions break engineering_standards.md section 2, \"A metric's "
            "description\": " + "; ".join(faults)
        )

    out = io.StringIO()
    out.write(HEADER)
    for name in sorted(blocks):
        # Never break a hyphenated term: the newline collapses in the warehouse and splits it.
        body = "\n".join(textwrap.wrap(blocks[name], width=WRAP,
                                       break_on_hyphens=False,
                                       break_long_words=False)) or blocks[name]
        out.write("\n\n")
        out.write("{% docs " + name + " %}\n")
        out.write(body + "\n")
        out.write("{% enddocs %}\n")

    # Canonical LF: checkouts differ in line endings, so `_same()` compares normalised and
    # `_to_disk()` matches the file's existing endings.
    return out.getvalue().encode("utf-8")


def _variant(column: str) -> str:
    """Which part of its metric a column holds, from its name; empty for the metric over the row."""
    def first(affixes: tuple[tuple[str, str, str], ...]) -> str:
        return next((token for kind, affix, token in affixes
                     if (column.startswith(affix) if kind == "prefix" else column.endswith(affix))),
                    "")
    return "_".join(part for part in (first(VARIANT_SIDES), first(VARIANT_PERIODS)) if part)


def _metric_of(block: str, metrics: set[str]) -> str:
    stem = block if block in metrics else block.rpartition("__")[0]
    if stem in metrics:
        return stem
    hit = _decompose(stem, metrics)
    if not hit:
        raise Abort("the block " + block + " names no catalogue metric")
    return hit[0]


def _long_rows(model: str, column: dict, names: set[str], window: str,
               metrics: set[str]) -> set[tuple[str, ...]]:
    """One row per metric a long-format mart holds, read from its metric_key's accepted_values."""
    values = next((t["accepted_values"].get("values") for t in column.get("tests") or []
                   if isinstance(t, dict) and isinstance(t.get("accepted_values"), dict)), None)
    if not values:
        raise Abort(model + "." + METRIC_KEY_COLUMN + " pins no accepted_values, so the "
                    "metrics it holds cannot be read")
    value_column = next((c for c in LONG_VALUE_COLUMNS if c in names), None)
    if value_column is None:
        raise Abort(model + " has a " + METRIC_KEY_COLUMN + " but none of "
                    + ", ".join(LONG_VALUE_COLUMNS) + " to hold its value")
    unknown = sorted(set(values) - metrics)
    if unknown:
        raise Abort(model + "." + METRIC_KEY_COLUMN + " holds values the catalogue does not "
                    "define: " + ", ".join(unknown))
    return {(model, value_column, value, "", window, METRIC_KEY_COLUMN) for value in values}


def _map_rows(rows: list[dict], names: list[str]) -> list[tuple[str, ...]]:
    metrics = {r["metric_id"].strip() for r in rows}
    blocks = set(_blocks(rows)) | set(_derived_blocks(rows, names))
    out: set[tuple[str, ...]] = set()
    for path in sorted((MODELS / MARTS_DIR).rglob("*.yml")):
        for model, columns in _models_in(path):
            here = {col["name"] for col in columns}
            window = WINDOW_COLUMN if WINDOW_COLUMN in here else ""
            for col in columns:
                for ref in DOC_REF.findall(str(col.get("description") or "")):
                    if ref in blocks:
                        out.add((model, col["name"], _metric_of(ref, metrics),
                                 _variant(col["name"]), window, ""))
                if col["name"] == METRIC_KEY_COLUMN:
                    out |= _long_rows(model, col, here, window, metrics)
    return sorted(out)


def _render_map(rows: list[dict], names: list[str]) -> bytes:
    map_rows = _map_rows(rows, names)
    missing = sorted({r["metric_id"].strip() for r in rows} - {row[2] for row in map_rows})
    if missing:
        raise Abort("these catalogue metrics have no mart column, so the map cannot say where "
                    "to read them: " + ", ".join(missing))
    out = io.StringIO()
    writer = csv.writer(out, lineterminator="\n")
    writer.writerow(MAP_FIELDS)
    writer.writerows(map_rows)
    return out.getvalue().encode("utf-8")


def _same(a: bytes, b: bytes) -> bool:
    """Byte equality that ignores line endings, because the checkout decides them."""
    return a.replace(b"\r\n", b"\n") == b.replace(b"\r\n", b"\n")


def _to_disk(canonical: bytes, existing: bytes | None) -> bytes:
    """The canonical text in the line endings the file on disk already uses; LF for a new file."""
    if existing is not None and b"\r\n" in existing:
        return canonical.replace(b"\n", b"\r\n")
    return canonical


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify the files match the seed and the model YAML. Writes nothing; "
             "exits 1 on drift.",
    )
    args = parser.parse_args()

    refused: list[str] = []
    try:
        rows = _read_rows()
        names = _column_names()
        expected = _render(rows, names, refused)
        expected_map = _render_map(rows, names)
    except Abort as exc:
        print("sync_metric_docs_blocks: " + str(exc), file=sys.stderr)
        return 1

    if refused:
        # Printed on both paths because it is the only place these columns are visible.
        print("NO BLOCK GENERATED, " + str(len(refused)) + " column name(s). The "
              "affix totals a metric that is already a rate, which is a different "
              "quantity. These stay blank on purpose:")
        for name in sorted(refused):
            print("  " + name)
        print()

    count = expected.count(b"{% docs ")
    map_count = expected_map.count(b"\n") - 1
    targets = (
        (OUT, expected, _describe_drift, str(count) + " blocks"),
        (MAP_OUT, expected_map, _describe_map_drift, str(map_count) + " map rows"),
    )

    if args.check:
        failed = False
        for path, want, describe, _ in targets:
            current = path.read_bytes() if path.exists() else None
            if current is None:
                print("FAIL: " + _rel(path) + " does not exist. Run "
                      "`python scripts/sync_metric_docs_blocks.py` to create it.")
                failed = True
            elif not _same(current, want):
                print("FAIL: " + _rel(path) + " has drifted from "
                      + _rel(SEED) + " or from the model YAML.\n")
                for line in describe(current, want):
                    print("  - " + line)
                failed = True
        if failed:
            print("\nThe seed and the model YAML are the sources. Do not edit the "
                  "generated files: run\n  python scripts/sync_metric_docs_blocks.py")
            return 1
        print("OK: " + str(count) + " metric docs blocks and " + str(map_count)
              + " metric map rows match " + _rel(SEED) + " and the model YAML.")
        return 0

    written = 0
    for path, want, _, what in targets:
        current = path.read_bytes() if path.exists() else None
        if current is not None and _same(current, want):
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(_to_disk(want, current))
        print("WROTE " + _rel(path) + ": " + what + " from " + _rel(SEED) + ".")
        written += 1
    if not written:
        # Exits non-zero so a generator that does nothing cannot pass for a working one.
        print("sync_metric_docs_blocks: already up to date (" + str(count)
              + " blocks, " + str(map_count) + " map rows). Nothing written.",
              file=sys.stderr)
        return 1
    return 0


def _rel(path: pathlib.Path) -> str:
    try:
        return str(path.relative_to(REPO_ROOT)).replace("\\", "/")
    except ValueError:
        return str(path)


def _describe_drift(current: bytes, expected: bytes) -> list[str]:
    """Name the blocks that differ, so a failure is actionable without a diff tool."""
    def parse(blob: bytes) -> dict[str, str]:
        text = blob.decode("utf-8", errors="replace")
        found = {}
        for m in re.finditer(r"\{%\s*docs\s+(\w+)\s*%\}(.*?)\{%\s*enddocs\s*%\}",
                             text, re.DOTALL):
            found[m.group(1)] = " ".join(m.group(2).split())
        return found

    now, want = parse(current), parse(expected)
    lines = []
    for name in sorted(set(want) - set(now)):
        lines.append("missing block: " + name)
    for name in sorted(set(now) - set(want)):
        lines.append("block no longer in the seed: " + name)
    for name in sorted(set(now) & set(want)):
        if now[name] != want[name]:
            lines.append("changed: " + name)
    if not lines:
        lines.append(
            "the blocks all match but the bytes do not: formatting, ordering or "
            "line endings differ. Regenerate rather than hand-fixing."
        )
    return lines


def _describe_map_drift(current: bytes, expected: bytes) -> list[str]:
    """Name the map rows that differ."""
    def parse(blob: bytes) -> set[tuple[str, ...]]:
        text = blob.decode("utf-8", errors="replace").replace("\r\n", "\n")
        return {tuple(row) for row in csv.reader(io.StringIO(text))}

    now, want = parse(current), parse(expected)
    lines = ["missing row: " + ",".join(row) for row in sorted(want - now)]
    lines += ["row no longer generated: " + ",".join(row) for row in sorted(now - want)]
    return lines or ["the rows all match but the bytes do not: ordering or quoting differ. "
                     "Regenerate rather than hand-fixing."]


